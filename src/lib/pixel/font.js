// 3x5 bitmap font for tiny in-scene lettering (shop signs, labels)
const GLYPHS = {
  A: ['###', '#.#', '###', '#.#', '#.#'],
  B: ['##.', '#.#', '##.', '#.#', '##.'],
  C: ['###', '#..', '#..', '#..', '###'],
  D: ['##.', '#.#', '#.#', '#.#', '##.'],
  E: ['###', '#..', '##.', '#..', '###'],
  G: ['###', '#..', '#.#', '#.#', '###'],
  H: ['#.#', '#.#', '###', '#.#', '#.#'],
  I: ['###', '.#.', '.#.', '.#.', '###'],
  L: ['#..', '#..', '#..', '#..', '###'],
  M: ['#.#', '###', '###', '#.#', '#.#'],
  N: ['##.', '#.#', '#.#', '#.#', '#.#'],
  O: ['###', '#.#', '#.#', '#.#', '###'],
  P: ['###', '#.#', '###', '#..', '#..'],
  R: ['##.', '#.#', '##.', '#.#', '#.#'],
  S: ['###', '#..', '###', '..#', '###'],
  T: ['###', '.#.', '.#.', '.#.', '.#.'],
  U: ['#.#', '#.#', '#.#', '#.#', '###'],
  V: ['#.#', '#.#', '#.#', '#.#', '.#.'],
  W: ['#.#', '#.#', '###', '###', '#.#'],
  Y: ['#.#', '#.#', '.#.', '.#.', '.#.'],
  K: ['#.#', '#.#', '##.', '#.#', '#.#'],
  F: ['###', '#..', '##.', '#..', '#..'],
  ' ': ['...', '...', '...', '...', '...'],
};

export function textWidth(text) {
  return text.length * 4 - 1;
}

export function drawText(pc, text, x, y, color) {
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch] || GLYPHS[' '];
    glyph.forEach((row, gy) => {
      [...row].forEach((cell, gx) => {
        if (cell === '#') pc.px(x + i * 4 + gx, y + gy, color);
      });
    });
  });
}
